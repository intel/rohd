set -euo pipefail

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd -- "$script_dir/../.." && pwd)"
extension_dir="$repo_root/rohd_devtools_extension"
cd "$extension_dir"

mode="${1:-}"
overrides="pubspec_overrides.yaml"
source_state=".devtools_dependency_sources"
marker="# Generated by scripts/devtools_dev_mode.sh. Do not edit by hand."
widgets_overrides="$repo_root/packages/rohd_devtools_widgets/pubspec_overrides.yaml"

default_rohd_path="$repo_root"
default_release_dir="$HOME/release"
if [[ -d "$HOME/true-release" ]]; then
  default_release_dir="$HOME/true-release"
fi

rohd_path="${ROHD_LOCAL_PATH:-$default_rohd_path}"
wave_viewer_path="${WAVE_VIEWER_LOCAL_PATH:-${RELEASE_DIR:-$default_release_dir}/rohd-wave-viewer}"
schematic_viewer_path="${SCHEMATIC_VIEWER_LOCAL_PATH:-${RELEASE_DIR:-$default_release_dir}/rohd-schematic-viewer}"

rohd_git_url="${ROHD_GIT_URL:-https://github.com/intel/rohd.git}"
rohd_git_ref="${ROHD_GIT_REF:-main}"
wave_viewer_git_url="${WAVE_VIEWER_GIT_URL:-https://github.com/intel/rohd-wave-viewer.git}"
wave_viewer_git_ref="${WAVE_VIEWER_GIT_REF:-main}"
schematic_viewer_git_url="${SCHEMATIC_VIEWER_GIT_URL:-https://github.com/intel/rohd-schematic-viewer.git}"
schematic_viewer_git_ref="${SCHEMATIC_VIEWER_GIT_REF:-main}"

packages=(
  rohd
  rohd_hierarchy
  rohd_waveform
  rohd_devtools_widgets
  rohd_source_navigator
  dart_wellen
  rohd_wave_viewer
  rohd_schematic_viewer
)

declare -A sources=(
  [rohd]=local
  [rohd_hierarchy]=local
  [rohd_waveform]=local
  [rohd_devtools_widgets]=local
  [rohd_source_navigator]=local
  [dart_wellen]=hosted
  [rohd_wave_viewer]=hosted
  [rohd_schematic_viewer]=hosted
)

use_workspace_resolution=true

usage() {
  cat <<'USAGE'
Usage: tool/devtools/devtools_dev_mode.sh <mode>

Configure individual package sources:
  tool/devtools/devtools_dev_mode.sh configure <package> <source> ...
  where each source is hosted, git, or local.

Configure a package bundle:
  tool/devtools/devtools_dev_mode.sh configure-group <group> <source>

Configure an external viewer for a VS Code task:
  tool/devtools/devtools_dev_mode.sh configure-interactive \
    <wave-viewer|schematic-viewer> <source>

Dependency groups:
  rohd               The fundamental rohd package
  rohd-packages      rohd_hierarchy, rohd_waveform,
                     rohd_devtools_widgets, and rohd_source_navigator
  wave-viewer        rohd_wave_viewer and dart_wellen
  schematic-viewer   rohd_schematic_viewer
  all                Every ROHD and viewer dependency

Other modes:
  manifest           Use the hosted dependencies from pubspec.yaml
  local-all          Use local checkouts for every dependency
  show               Print the saved source selection and generated overrides

Workspace packages resolve locally by default. ROHD_LOCAL_PATH is used only
when the extension is switched to an independent resolution for hosted or Git
dependencies.

Local checkout defaults for external viewer packages:
  WAVE_VIEWER_LOCAL_PATH       Wave Viewer checkout
  SCHEMATIC_VIEWER_LOCAL_PATH  Schematic Viewer checkout

If ~/true-release exists, viewer paths default below it; otherwise they default
below ~/release. RELEASE_DIR changes both viewer defaults.

Git sources use the package's public repository and main branch by default.
Override them with ROHD_GIT_URL / ROHD_GIT_REF,
WAVE_VIEWER_GIT_URL / WAVE_VIEWER_GIT_REF, and
SCHEMATIC_VIEWER_GIT_URL / SCHEMATIC_VIEWER_GIT_REF. VS Code tasks can
instead provide ROHD_GIT_SOURCE, WAVE_VIEWER_GIT_SOURCE, or
SCHEMATIC_VIEWER_GIT_SOURCE as `repository:ref`.

configure-interactive prompts only for the selected external viewer source:
local asks for a checkout path, git asks once for `repository:ref` (for
example `github.com/intel/rohd-wave-viewer:main`), and hosted needs no
additional input. GitHub repository inputs do not need an `https://` prefix.
USAGE
}

validate_source() {
  case "$1" in
    hosted|git|local) ;;
    *)
      echo "Invalid dependency source '$1'; expected hosted, git, or local." >&2
      exit 2
      ;;
  esac
}

validate_package() {
  case "$1" in
    rohd|rohd_hierarchy|rohd_waveform|rohd_devtools_widgets|\
      rohd_source_navigator|dart_wellen|rohd_wave_viewer|\
      rohd_schematic_viewer) ;;
    *)
      echo "Unsupported package '$1'." >&2
      echo "Supported packages: ${packages[*]}." >&2
      exit 2
      ;;
  esac
}

is_workspace_package() {
  case "$1" in
    rohd|rohd_hierarchy|rohd_waveform|rohd_devtools_widgets|\
      rohd_source_navigator) return 0 ;;
    *) return 1 ;;
  esac
}

ensure_managed_or_absent() {
  local file="$1"

  if [[ -f "$file" ]] && ! grep -qxF "$marker" "$file"; then
    echo "$file exists and was not generated by this script." >&2
    echo "Move or remove it before switching development modes." >&2
    exit 1
  fi
}

resolve_directory() {
  local path="$1"

  case "$path" in
    '~') path="$HOME" ;;
    \~/*) path="$HOME/${path:2}" ;;
  esac
  if [[ ! -d "$path" ]]; then
    echo "Could not find local checkout: $path" >&2
    exit 1
  fi
  (cd -- "$path" && pwd)
}

resolve_saved_paths() {
  local package
  for package in "${packages[@]}"; do
    [[ "${sources[$package]}" == local ]] || continue
    case "$package" in
      rohd|rohd_hierarchy|rohd_waveform|rohd_devtools_widgets|rohd_source_navigator)
        rohd_path="$(resolve_directory "$rohd_path")"
        ;;
      dart_wellen|rohd_wave_viewer)
        wave_viewer_path="$(resolve_directory "$wave_viewer_path")"
        ;;
      rohd_schematic_viewer)
        schematic_viewer_path="$(resolve_directory "$schematic_viewer_path")"
        ;;
    esac
  done
}

widgets_local_path() {
  local path="$rohd_path/packages/rohd_devtools_widgets"
  if [[ ! -f "$path/pubspec.yaml" ]]; then
    path="$rohd_path/rohd_devtools_extension/packages/rohd_devtools_widgets"
  fi
  printf '%s' "$path"
}

navigator_local_path() {
  local path="$rohd_path/packages/rohd_source_navigator"
  if [[ ! -f "$path/pubspec.yaml" ]]; then
    path="$rohd_path/rohd_extension/dart"
  fi
  printf '%s' "$path"
}

local_package_path() {
  case "$1" in
    rohd) printf '%s' "$rohd_path" ;;
    rohd_hierarchy) printf '%s' "$rohd_path/packages/rohd_hierarchy" ;;
    rohd_waveform) printf '%s' "$rohd_path/packages/rohd_waveform" ;;
    rohd_devtools_widgets) widgets_local_path ;;
    rohd_source_navigator) navigator_local_path ;;
    dart_wellen) printf '%s' "$wave_viewer_path/packages/dart_wellen" ;;
    rohd_wave_viewer) printf '%s' "$wave_viewer_path" ;;
    rohd_schematic_viewer) printf '%s' "$schematic_viewer_path" ;;
  esac
}

validate_local_package() {
  local package="$1"
  local path

  path="$(local_package_path "$package")"
  if [[ ! -f "$path/pubspec.yaml" ]]; then
    echo "Missing local package $package: $path/pubspec.yaml" >&2
    exit 1
  fi
}

git_package_url() {
  case "$1" in
    rohd|rohd_hierarchy|rohd_waveform|rohd_devtools_widgets|\
      rohd_source_navigator)
      printf '%s' "$rohd_git_url"
      ;;
    dart_wellen|rohd_wave_viewer)
      printf '%s' "$wave_viewer_git_url"
      ;;
    rohd_schematic_viewer)
      printf '%s' "$schematic_viewer_git_url"
      ;;
  esac
}

git_package_ref() {
  case "$1" in
    rohd|rohd_hierarchy|rohd_waveform|rohd_devtools_widgets|\
      rohd_source_navigator)
      printf '%s' "$rohd_git_ref"
      ;;
    dart_wellen|rohd_wave_viewer)
      printf '%s' "$wave_viewer_git_ref"
      ;;
    rohd_schematic_viewer)
      printf '%s' "$schematic_viewer_git_ref"
      ;;
  esac
}

git_package_path() {
  case "$1" in
    rohd|rohd_wave_viewer|rohd_schematic_viewer) printf '%s' "" ;;
    rohd_hierarchy) printf '%s' "packages/rohd_hierarchy" ;;
    rohd_waveform) printf '%s' "packages/rohd_waveform" ;;
    rohd_devtools_widgets) printf '%s' "packages/rohd_devtools_widgets" ;;
    rohd_source_navigator) printf '%s' "packages/rohd_source_navigator" ;;
    dart_wellen) printf '%s' "packages/dart_wellen" ;;
  esac
}

append_dependency_override() {
  local package="$1"
  local file="${2:-$overrides}"
  local source="${sources[$package]}"
  local path

  case "$source" in
    hosted) return ;;
    local)
      if is_workspace_package "$package" && [[ "$use_workspace_resolution" == true ]]; then
        return
      fi
      path="$(local_package_path "$package")"
      printf '  %s:\n    path: %s\n' "$package" "$path" >>"$file"
      ;;
    git)
      cat >>"$file" <<YAML
  $package:
    git:
      url: $(git_package_url "$package")
      ref: $(git_package_ref "$package")
YAML
      path="$(git_package_path "$package")"
      if [[ -n "$path" ]]; then
        printf '      path: %s\n' "$path" >>"$file"
      fi
      ;;
  esac
}

package_override_block() {
  local package="$1"

  awk -v header="  $package:" '
    $0 == header {
      found = 1
      next
    }
    found && /^  [a-zA-Z0-9_]+:/ {
      exit
    }
    found {
      print
    }
  ' "$overrides"
}

infer_sources_from_overrides() {
  local block
  local package
  local path

  if [[ ! -f "$overrides" ]] || ! grep -qxF "$marker" "$overrides"; then
    return
  fi
  if grep -q '^resolution:[[:space:]]*$' "$overrides"; then
    sources[rohd]=hosted
    sources[rohd_hierarchy]=hosted
    sources[rohd_waveform]=hosted
    sources[rohd_devtools_widgets]=hosted
    sources[rohd_source_navigator]=hosted
  fi
  for package in "${packages[@]}"; do
    block="$(package_override_block "$package")"
    if grep -q '^    git:' <<<"$block"; then
      sources["$package"]=git
    elif grep -q '^    path:' <<<"$block"; then
      sources["$package"]=local
      path="$(awk '$1 == "path:" { print $2; exit }' <<<"$block")"
      case "$package" in
        rohd) rohd_path="$path" ;;
        rohd_wave_viewer) wave_viewer_path="$path" ;;
        rohd_schematic_viewer) schematic_viewer_path="$path" ;;
      esac
    fi
  done
}

load_source_state() {
  local key
  local value

  if [[ ! -f "$source_state" ]]; then
    infer_sources_from_overrides
    return
  fi
  while IFS='=' read -r key value; do
    case "$key" in
      rohd|rohd_hierarchy|rohd_waveform|rohd_devtools_widgets|\
        rohd_source_navigator|dart_wellen|rohd_wave_viewer|\
        rohd_schematic_viewer)
        sources["$key"]="$value"
        ;;
      rohd_git_ref) rohd_git_ref="$value" ;;
      rohd_git_url) rohd_git_url="$value" ;;
      rohd_local_path) rohd_path="$value" ;;
      wave_viewer_git_ref) wave_viewer_git_ref="$value" ;;
      wave_viewer_git_url) wave_viewer_git_url="$value" ;;
      wave_viewer_local_path) wave_viewer_path="$value" ;;
      schematic_viewer_git_ref) schematic_viewer_git_ref="$value" ;;
      schematic_viewer_git_url) schematic_viewer_git_url="$value" ;;
      schematic_viewer_local_path) schematic_viewer_path="$value" ;;
    esac
  done <"$source_state"
}

write_source_state() {
  local package

  : >"$source_state"
  for package in "${packages[@]}"; do
    printf '%s=%s\n' "$package" "${sources[$package]}" >>"$source_state"
  done
  cat >>"$source_state" <<STATE
rohd_git_ref=$rohd_git_ref
rohd_git_url=$rohd_git_url
rohd_local_path=$rohd_path
wave_viewer_git_ref=$wave_viewer_git_ref
wave_viewer_git_url=$wave_viewer_git_url
wave_viewer_local_path=$wave_viewer_path
schematic_viewer_git_ref=$schematic_viewer_git_ref
schematic_viewer_git_url=$schematic_viewer_git_url
schematic_viewer_local_path=$schematic_viewer_path
STATE
}

write_overrides() {
  local package
  local has_external_workspace_source=false

  ensure_managed_or_absent "$overrides"
  resolve_saved_paths
  for package in "${packages[@]}"; do
    validate_source "${sources[$package]}"
    if [[ "${sources[$package]}" == "local" ]]; then
      validate_local_package "$package"
    fi
    if is_workspace_package "$package" &&
      [[ "${sources[$package]}" != "local" ]]; then
      has_external_workspace_source=true
    fi
  done

  use_workspace_resolution=true
  if [[ "$has_external_workspace_source" == true ]]; then
    use_workspace_resolution=false
  fi

  cat >"$overrides" <<YAML
$marker
# This file is intentionally ignored by git.
YAML
  if [[ "$use_workspace_resolution" == false ]]; then
    printf 'resolution:\n' >>"$overrides"
  fi
  cat >>"$overrides" <<YAML
dependency_overrides:
  cupertino_ui: ">=1.0.0 <1.1.0"
YAML
  for package in "${packages[@]}"; do
    append_dependency_override "$package"
  done
  if [[ -f "$widgets_overrides" ]]; then
    ensure_managed_or_absent "$widgets_overrides"
    rm -f -- "$widgets_overrides"
  fi
  if [[ "$use_workspace_resolution" == true ]]; then
    echo "Wrote $overrides; in-repository packages resolve from the Pub workspace."
  else
    echo "Wrote $overrides for independent dependency resolution."
  fi
}

set_group_source() {
  local group="$1"
  local source="$2"

  validate_source "$source"
  case "$group" in
    rohd)
      sources[rohd]="$source"
      ;;
    rohd-packages)
      sources[rohd_hierarchy]="$source"
      sources[rohd_waveform]="$source"
      sources[rohd_devtools_widgets]="$source"
      sources[rohd_source_navigator]="$source"
      ;;
    wave-viewer)
      sources[dart_wellen]="$source"
      sources[rohd_wave_viewer]="$source"
      ;;
    schematic-viewer)
      sources[rohd_schematic_viewer]="$source"
      ;;
    all)
      local package
      for package in "${packages[@]}"; do
        sources["$package"]="$source"
      done
      ;;
    *)
      echo "Invalid dependency group '$group'." >&2
      echo "Expected rohd, rohd-packages, wave-viewer, schematic-viewer, or all." >&2
      exit 2
      ;;
  esac
}

apply_environment_for_group() {
  local group="$1"
  local source="$2"

  case "$group" in
    rohd|rohd-packages)
      if [[ "$source" == "git" ]]; then
        if [[ -n "${ROHD_GIT_SOURCE:-}" ]]; then
          configure_git_source rohd "$ROHD_GIT_SOURCE"
        else
          rohd_git_url="${ROHD_GIT_URL:-$rohd_git_url}"
          rohd_git_ref="${ROHD_GIT_REF:-$rohd_git_ref}"
        fi
      elif [[ "$source" == "local" ]]; then
        rohd_path="${ROHD_LOCAL_PATH:-$rohd_path}"
      fi
      ;;
    wave-viewer)
      if [[ "$source" == "git" ]]; then
        if [[ -n "${WAVE_VIEWER_GIT_SOURCE:-}" ]]; then
          configure_git_source wave-viewer "$WAVE_VIEWER_GIT_SOURCE"
        else
          wave_viewer_git_url="${WAVE_VIEWER_GIT_URL:-$wave_viewer_git_url}"
          wave_viewer_git_ref="${WAVE_VIEWER_GIT_REF:-$wave_viewer_git_ref}"
        fi
      elif [[ "$source" == "local" ]]; then
        wave_viewer_path="${WAVE_VIEWER_LOCAL_PATH:-$wave_viewer_path}"
      fi
      ;;
    schematic-viewer)
      if [[ "$source" == "git" ]]; then
        if [[ -n "${SCHEMATIC_VIEWER_GIT_SOURCE:-}" ]]; then
          configure_git_source schematic-viewer "$SCHEMATIC_VIEWER_GIT_SOURCE"
        else
          schematic_viewer_git_url="${SCHEMATIC_VIEWER_GIT_URL:-$schematic_viewer_git_url}"
          schematic_viewer_git_ref="${SCHEMATIC_VIEWER_GIT_REF:-$schematic_viewer_git_ref}"
        fi
      elif [[ "$source" == "local" ]]; then
        schematic_viewer_path="${SCHEMATIC_VIEWER_LOCAL_PATH:-$schematic_viewer_path}"
      fi
      ;;
    all)
      if [[ "$source" == "git" ]]; then
        if [[ -n "${ROHD_GIT_SOURCE:-}" ]]; then
          configure_git_source rohd "$ROHD_GIT_SOURCE"
        else
          rohd_git_url="${ROHD_GIT_URL:-$rohd_git_url}"
          rohd_git_ref="${ROHD_GIT_REF:-$rohd_git_ref}"
        fi
        if [[ -n "${WAVE_VIEWER_GIT_SOURCE:-}" ]]; then
          configure_git_source wave-viewer "$WAVE_VIEWER_GIT_SOURCE"
        else
          wave_viewer_git_url="${WAVE_VIEWER_GIT_URL:-$wave_viewer_git_url}"
          wave_viewer_git_ref="${WAVE_VIEWER_GIT_REF:-$wave_viewer_git_ref}"
        fi
        if [[ -n "${SCHEMATIC_VIEWER_GIT_SOURCE:-}" ]]; then
          configure_git_source schematic-viewer "$SCHEMATIC_VIEWER_GIT_SOURCE"
        else
          schematic_viewer_git_url="${SCHEMATIC_VIEWER_GIT_URL:-$schematic_viewer_git_url}"
          schematic_viewer_git_ref="${SCHEMATIC_VIEWER_GIT_REF:-$schematic_viewer_git_ref}"
        fi
      elif [[ "$source" == "local" ]]; then
        rohd_path="${ROHD_LOCAL_PATH:-$rohd_path}"
        wave_viewer_path="${WAVE_VIEWER_LOCAL_PATH:-$wave_viewer_path}"
        schematic_viewer_path="${SCHEMATIC_VIEWER_LOCAL_PATH:-$schematic_viewer_path}"
      fi
      ;;
  esac
}

configure_group() {
  local group="${1:-}"
  local source="${2:-}"

  if [[ "$#" -ne 2 ]]; then
    echo "Usage: $0 configure-group <group> <hosted|git|local>" >&2
    exit 2
  fi
  load_source_state
  set_group_source "$group" "$source"
  apply_environment_for_group "$group" "$source"
  write_overrides
  write_source_state
}

prompt_value() {
  local label="$1"
  local default_value="$2"
  local value

  printf '%s [%s]: ' "$label" "$default_value" >&2
  if ! IFS= read -r value; then
    echo "error: Could not read $label." >&2
    return 1
  fi
  value="${value:-$default_value}"
  if [[ -z "$value" ]]; then
    echo "error: $label cannot be empty." >&2
    return 1
  fi
  printf '%s' "$value"
}

display_git_source() {
  local url="$1"
  local ref="$2"

  case "$url" in
    https://github.com/*)
      url="${url#https://}"
      url="${url%.git}"
      ;;
  esac
  printf '%s:%s' "$url" "$ref"
}

configure_git_source() {
  local target="$1"
  local spec="$2"
  local url
  local ref

  if [[ "$spec" != *:* ]]; then
    echo "Git source '$spec' must use the format repository:ref." >&2
    exit 2
  fi
  url="${spec%:*}"
  ref="${spec##*:}"
  if [[ -z "$url" || -z "$ref" || "$ref" == //* ]]; then
    echo "Git source '$spec' must use the format repository:ref." >&2
    exit 2
  fi
  case "$url" in
    github.com/*) url="https://$url" ;;
  esac

  case "$target" in
    rohd)
      rohd_git_url="$url"
      rohd_git_ref="$ref"
      ;;
    wave-viewer)
      wave_viewer_git_url="$url"
      wave_viewer_git_ref="$ref"
      ;;
    schematic-viewer)
      schematic_viewer_git_url="$url"
      schematic_viewer_git_ref="$ref"
      ;;
    *)
      echo "Unsupported Git source target '$target'." >&2
      exit 2
      ;;
  esac
}

configure_interactive_viewer_group() {
  local group="${1:-}"
  local source="${2:-}"

  if [[ "$#" -ne 2 ]]; then
    echo "Usage: $0 configure-interactive <wave-viewer|schematic-viewer> <hosted|git|local>" >&2
    exit 2
  fi
  case "$group" in
    wave-viewer|schematic-viewer) ;;
    *)
      echo "configure-interactive supports wave-viewer or schematic-viewer." >&2
      exit 2
      ;;
  esac

  load_source_state
  validate_source "$source"
  case "$group:$source" in
    wave-viewer:local)
      wave_viewer_path="$(prompt_value \
        "Wave Viewer checkout/worktree path" "$wave_viewer_path")"
      ;;
    wave-viewer:git)
      configure_git_source wave-viewer "$(prompt_value \
        "Wave Viewer Git repository:ref" \
        "$(display_git_source "$wave_viewer_git_url" "$wave_viewer_git_ref")")"
      ;;
    schematic-viewer:local)
      schematic_viewer_path="$(prompt_value \
        "Schematic Viewer checkout/worktree path" "$schematic_viewer_path")"
      ;;
    schematic-viewer:git)
      configure_git_source schematic-viewer "$(prompt_value \
        "Schematic Viewer Git repository:ref" \
        "$(display_git_source \
          "$schematic_viewer_git_url" "$schematic_viewer_git_ref")")"
      ;;
  esac

  set_group_source "$group" "$source"
  apply_environment_for_group "$group" "$source"
  write_overrides
  write_source_state
}

configure_packages() {
  local package
  local source

  if [[ "$#" -eq 0 || "$(( $# % 2 ))" -ne 0 ]]; then
    echo "Usage: $0 configure <package> <hosted|git|local> ..." >&2
    exit 2
  fi
  load_source_state
  while [[ "$#" -gt 0 ]]; do
    package="$1"
    source="$2"
    shift 2
    validate_package "$package"
    validate_source "$source"
    sources["$package"]="$source"
    case "$package" in
      rohd) apply_environment_for_group rohd "$source" ;;
      rohd_hierarchy|rohd_waveform|rohd_devtools_widgets|rohd_source_navigator)
        apply_environment_for_group rohd-packages "$source"
        ;;
      dart_wellen|rohd_wave_viewer)
        apply_environment_for_group wave-viewer "$source"
        ;;
      rohd_schematic_viewer)
        apply_environment_for_group schematic-viewer "$source"
        ;;
    esac
  done
  write_overrides
  write_source_state
}

show_configuration() {
  if [[ -f "$source_state" ]]; then
    echo "Dependency sources:"
    cat "$source_state"
  else
    echo "No saved dependency selection; using pubspec.yaml."
  fi
  if [[ -f "$overrides" ]]; then
    echo
    echo "$overrides:"
    cat "$overrides"
  else
    echo "No generated override file is present."
  fi
}

case "$mode" in
  configure)
    shift
    configure_packages "$@"
    ;;
  configure-group)
    configure_group "${2:-}" "${3:-}"
    ;;
  configure-interactive)
    configure_interactive_viewer_group "${2:-}" "${3:-}"
    ;;
  manifest)
    rm -f -- "$source_state"
    set_group_source all hosted
    write_overrides
    ;;
  local-all)
    set_group_source all local
