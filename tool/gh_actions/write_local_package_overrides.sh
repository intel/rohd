# write_local_package_overrides.sh
# Creates ignored overrides for workspace compatibility and the standalone
# tutorial example.

set -euo pipefail

readonly SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
readonly REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"

write_override() {
  local file="$1"
  local contents="$2"
  if [[ -e "$file" ]]; then
    return
  fi
  printf '%s\n' "$contents" > "$file"
}

write_override \
  "$REPO_ROOT/doc/tutorials/chapter_9/rohd_vf_example/pubspec_overrides.yaml" \
'dependency_overrides:
  rohd:
    path: ../../../../
  rohd_hierarchy:
    path: ../../../../packages/rohd_hierarchy'

write_override \
  "$REPO_ROOT/rohd_devtools_extension/pubspec_overrides.yaml" \
'# Generated by scripts/devtools_dev_mode.sh. Do not edit by hand.
# This file is intentionally ignored by git.
dependency_overrides:
  cupertino_ui: ">=1.0.0 <1.1.0"'
